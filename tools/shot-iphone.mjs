// iPhone 15 QA (Home Screen app size, landscape 852×393): node tools/shot-iphone.mjs <url> <out-prefix> [spawn]
import { chromium, devices } from '@playwright/test';
const url = process.argv[2] ?? 'http://localhost:5173/';
const out = process.argv[3] ?? 'tools/shots/ip';
const spawn = process.argv[4] ?? 'hub';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ ...devices['iPhone 15 landscape'], viewport: { width: 852, height: 393 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (m.type() !== 'debug') logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(url);
await page.waitForFunction(() => window.voltline?.state === 'menu', null, { timeout: 90000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-menu.png` });
await page.tap('.btn.primary');
await page.evaluate((s) => { window.voltline.respawn(s); }, spawn);
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}-ride.png` });
const cdp = await ctx.newCDPSession(page);
const tp = (id, x, y) => ({ x, y, id, radiusX: 5, radiusY: 5, force: 1 });
const thr = await page.locator('.t-throttle').boundingBox();
const T = tp(1, thr.x + thr.width / 2, thr.y + thr.height * 0.3);
const S = tp(2, 140, 300);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [T, S] });
await page.waitForTimeout(2500);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [T, { ...S, x: S.x + 40 }] });
await page.waitForTimeout(1500);
logs.push('[state] ' + JSON.stringify(await page.evaluate(() => { const g = window.voltline; const i = g.post ? { calls: g.post.sceneCalls, triangles: g.post.sceneTris } : g.renderer.info.render; return { inp: g.input.state, v: g.bike.speed.toFixed(1), lean: g.bike.lean.toFixed(2), fps: g.fps.toFixed(0), calls: i.calls, tris: i.triangles }; })));
await page.screenshot({ path: `${out}-ride2.png` });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
await page.tap('[data-action="pause"]');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}-pause.png` });
await page.evaluate(() => window.voltline.ui.openGarage());
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-garage.png` });
console.log(logs.join('\n'));
await browser.close();
